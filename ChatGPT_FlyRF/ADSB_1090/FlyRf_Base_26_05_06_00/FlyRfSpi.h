/*
  Модуль FlyRfSpi.h
  Назначение:
  - Публичный интерфейс управления доступом к SPI-шине.

  Что содержит файл:
  - Объявления функций инициализации, блокировки и разблокировки SPI.
  - RAII-обертку FlyRfSpiGuard для безопасного удержания шины в пределах области.
*/

#pragma once
#include <Arduino.h>

extern "C" void FlyRfSpiSetup();
extern "C" bool FlyRfSpiLock(uint32_t timeoutMs = 50);
extern "C" void FlyRfSpiUnlock();

struct FlyRfSpiGuard
{
    bool locked;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    explicit FlyRfSpiGuard(uint32_t timeoutMs = 50) : locked(FlyRfSpiLock(timeoutMs)) {}
//------------------------------------------------------------------------------
// Назначение функции: Выполняет логику функции `~FlyRfSpiGuard` и обрабатывает fly радиоканал spi guard в контексте модуля FlyRfSpi.h.
// Локальные переменные: явные локальные переменные не используются; функция работает через параметры, глобальные структуры и результаты вызовов.
//------------------------------------------------------------------------------
    ~FlyRfSpiGuard() { if (locked) FlyRfSpiUnlock(); }
//------------------------------------------------------------------------------
// Назначение функции: Выполняет логику функции `bool` и обрабатывает bool в контексте модуля FlyRfSpi.h.
// Локальные переменные: явные локальные переменные не используются; функция работает через параметры, глобальные структуры и результаты вызовов.
//------------------------------------------------------------------------------
    operator bool() const { return locked; }
};
