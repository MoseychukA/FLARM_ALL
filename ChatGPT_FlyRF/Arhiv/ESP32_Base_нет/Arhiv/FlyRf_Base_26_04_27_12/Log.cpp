/*
  Модуль Log.cpp
  Назначение:
  - Единый компактный журнал сообщений проекта.

  Основные задачи модуля:
  - Формировать строки логов с уровнем и тегом.
  - Передавать диагностические сообщения в основной Serial-порт.
  - Давать простой централизованный механизм отладки без дублирования кода.
*/

#include "Log.h"
#include <stdarg.h>
#include <stdio.h>

static bool g_logReady = false;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.

//------------------------------------------------------------------------------
// Назначение функции: Инициализирует log, подготавливает связанные объекты и включает работу соответствующего узла.
// Локальные переменные: явные локальные переменные не используются; функция работает через параметры, глобальные структуры и результаты вызовов.
//------------------------------------------------------------------------------
void Log_setup()
{
    g_logReady = true;
}

//------------------------------------------------------------------------------
// Назначение функции: Выполняет логику функции `Log_write` и обрабатывает log в контексте модуля Log.cpp.
// Локальные переменные: msg — временной параметр или отметка времени: используется для тайм-аутов, задержек, мигания или контроля давности данных; args — рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
// - msg: Временная отметка, интервал или значение тайм-аута.
// - args: Служебная переменная, используемая для промежуточных вычислений и логики модуля.
//------------------------------------------------------------------------------
void Log_write(const char* level, const char* tag, const char* fmt, ...)
{
    if (!g_logReady) return;
    char msg[192];  // Временной параметр или отметка времени: используется для тайм-аутов, задержек, мигания или контроля давности данных.
    va_list args;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    va_start(args, fmt);
    vsnprintf(msg, sizeof(msg), fmt, args);
    va_end(args);
    Serial.printf("[%s][%s] %s\r\n", level ? level : "?", tag ? tag : "APP", msg);
}
