/*
  Модуль TrafficTypes.h
  Назначение:
  - Базовые типы данных для промежуточного представления сторонней воздушной цели.

  Что содержит файл:
  - Перечень источников трафика.
  - Структуру TrafficCandidate, которая используется декодерами до записи данных в Container.
*/

#pragma once

#include <Arduino.h>

enum TrafficSource : uint8_t
{
    TRAFFIC_SOURCE_UNKNOWN = 0,
    TRAFFIC_SOURCE_FLARM_LORA = 1,
    TRAFFIC_SOURCE_ADSB_DUMP1090 = 2
};

struct TrafficCandidate
{
    uint32_t address;  // Параметр конфигурации: хранит выбранный режим, адрес, настройки модуля или пользовательское значение.
    float lat;  // Навигационный или геометрический параметр: координаты, угол, дальность, размер или положение объекта.
    float lon;  // Навигационный или геометрический параметр: координаты, угол, дальность, размер или положение объекта.
    int altitude;  // Навигационный или геометрический параметр: координаты, угол, дальность, размер или положение объекта.
    float speed;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    float course;  // Навигационный или геометрический параметр: координаты, угол, дальность, размер или положение объекта.
    uint32_t timestampMs;  // Временной параметр или отметка времени: используется для тайм-аутов, задержек, мигания или контроля давности данных.
    int rssi;  // Параметр радиоканала или протокола: описывает частоту, мощность, профиль, режим передачи или текущее состояние RF.
    float snr;  // Параметр радиоканала или протокола: описывает частоту, мощность, профиль, режим передачи или текущее состояние RF.
    TrafficSource source;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    bool valid;  // Логический флаг состояния: показывает, разрешена ли операция, активен ли режим или есть ли данные.
};
