typedef struct EEPROM_S {
    uint32_t   magic;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    uint32_t   version;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    settings_t settings;  // Структура настроек, состояния или набора рабочих данных.
} eeprom_struct_t;

typedef union EEPROM_U {
    eeprom_struct_t field;  // Рабочая переменная модуля: хранит промежуточное значение, используемое в текущей логике файла.
    uint8_t raw[sizeof(eeprom_struct_t)];
} eeprom_t;

