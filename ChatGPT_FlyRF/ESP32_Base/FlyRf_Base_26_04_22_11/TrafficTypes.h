/*
  Модуль TrafficTypes.h
  Назначение:
  - Базовые типы данных для промежуточного представления сторонней воздушной цели.

  Что содержит файл:
  - Перечень источников трафика.
  - Структуру TrafficCandidate, которая используется декодерами до записи данных в Container.
*/

#pragma once

#include <Arduino.h>

enum TrafficSource : uint8_t
{
    TRAFFIC_SOURCE_UNKNOWN = 0,
    TRAFFIC_SOURCE_FLARM_LORA = 1,
    TRAFFIC_SOURCE_ADSB_DUMP1090 = 2
};

struct TrafficCandidate
{
    uint32_t address;  // Параметр конфигурации интерфейса, адресации или выбранного режима.
    float lat;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    float lon;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    int altitude;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    float speed;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    float course;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    uint32_t timestampMs;  // Временная отметка, интервал или значение тайм-аута.
    int rssi;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    float snr;  // Числовой параметр навигации, радиообмена, геометрии или измерения.
    TrafficSource source;  // Служебная переменная, используемая для промежуточных вычислений и логики модуля.
    bool valid;  // Логический флаг состояния, разрешения или наличия данных.
};
