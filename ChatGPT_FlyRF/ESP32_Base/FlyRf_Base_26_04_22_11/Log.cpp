/*
  Модуль Log.cpp
  Назначение:
  - Единый компактный журнал сообщений проекта.

  Основные задачи модуля:
  - Формировать строки логов с уровнем и тегом.
  - Передавать диагностические сообщения в основной Serial-порт.
  - Давать простой централизованный механизм отладки без дублирования кода.
*/

#include "Log.h"
#include <stdarg.h>
#include <stdio.h>

static bool g_logReady = false;  // Логический флаг состояния, разрешения или наличия данных.

//------------------------------------------------------------------------------
// Назначение функции: Инициализирует модуль, подготавливает ресурсы и стартовые параметры.
// Локальные переменные: функция использует в основном параметры, глобальные объекты или выраженные локальные данные не требуются.
//------------------------------------------------------------------------------
void Log_setup()
{
    g_logReady = true;
}

//------------------------------------------------------------------------------
// Назначение функции: Выполняет отдельную законченную операцию внутри модуля и используется в общей логике проекта.
// Локальные переменные:
// - msg: Временная отметка, интервал или значение тайм-аута.
// - args: Служебная переменная, используемая для промежуточных вычислений и логики модуля.
//------------------------------------------------------------------------------
void Log_write(const char* level, const char* tag, const char* fmt, ...)
{
    if (!g_logReady) return;
    char msg[192];  // Временная отметка, интервал или значение тайм-аута.
    va_list args;  // Служебная переменная, используемая для промежуточных вычислений и логики модуля.
    va_start(args, fmt);
    vsnprintf(msg, sizeof(msg), fmt, args);
    va_end(args);
    Serial.printf("[%s][%s] %s\r\n", level ? level : "?", tag ? tag : "APP", msg);
}
